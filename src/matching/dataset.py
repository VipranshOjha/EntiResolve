"""
dataset.py — Supervised Pairwise Dataset Construction and Hard Negative Sampling.

Builds labeled pairwise feature datasets from:
- Positives: confirmed ground-truth matches
- Hard Negatives: candidates generated by Phase 3 composite blocking that are NOT ground-truth matches
Strictly respects train/validation separation.
"""

from __future__ import annotations

import random
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Callable, Sequence
import numpy as np

from src.blocking.composite import CompositeBlocker
from src.matching.features import CandidateProvenance, PairwiseFeatureExtractor
from src.matching.similarity import jaro_winkler_similarity
from src.normalization.record import BusinessRecord


@dataclass
class DatasetStats:
    """Summary statistics for constructed pairwise dataset."""
    num_queries: int
    num_positives: int
    num_negatives: int
    positive_ratio: float
    negatives_per_entity_mean: float
    strategy: str
    hardest_negative_sim_mean: float
    hardest_negative_sim_max: float


class PairwiseDatasetBuilder:
    """
    Constructs supervised pairwise training and validation datasets with configurable
    negative sampling strategies on Phase 3 blocker candidates.
    """

    def __init__(
        self,
        feature_extractor: PairwiseFeatureExtractor,
        seed: int = 42,
    ) -> None:
        self.feature_extractor = feature_extractor
        self.seed = seed
        self.rng = random.Random(seed)

    def build_pairs_for_query(
        self,
        s1_record: BusinessRecord,
        target_dict: dict[str, BusinessRecord],
        ground_truth_targets: set[str],
        candidates: list[str],
        blocker_attribution: dict[str, list[str]],
        negative_strategy: str = "random",
        negative_ratio: int = 5,
    ) -> tuple[list[tuple[BusinessRecord, BusinessRecord, CandidateProvenance, int]], dict[str, Any]]:
        """
        Build positive and negative pairs for a single S1 query entity.

        Parameters
        ----------
        s1_record:
            Normalized S1 BusinessRecord.
        target_dict:
            Lookup mapping entity_id -> normalized BusinessRecord for target records.
        ground_truth_targets:
            Set of target IDs that are true matches for this S1.
        candidates:
            Ranked list of candidate target IDs from CompositeBlocker.
        blocker_attribution:
            Dict mapping blocker_name -> list of candidate target IDs.
        negative_strategy:
            'all' (A), 'random' (B), 'hard_similarity' (C), or 'blocker_overlap' (D).
        negative_ratio:
            Max negatives per positive (or per S1 if no positives).

        Returns
        -------
        pairs:
            List of (s1_record, target_record, provenance, label) tuples.
        info:
            Metadata about candidates and negative distribution.
        """
        # Invert attribution for fast provenance lookup: target_id -> set of blockers
        candidate_blockers: dict[str, set[str]] = {}
        for b_name, targets in blocker_attribution.items():
            for tid in targets:
                if tid not in candidate_blockers:
                    candidate_blockers[tid] = set()
                candidate_blockers[tid].add(b_name)

        positives: list[tuple[BusinessRecord, BusinessRecord, CandidateProvenance, int]] = []
        neg_candidates_info: list[tuple[str, int, float, int]] = []  # (tid, rank, score, blocker_count)

        # 1. Process retrieved candidates
        retrieved_set = set(candidates)
        for rank, tid in enumerate(candidates, start=1):
            if tid not in target_dict:
                continue
            tgt = target_dict[tid]
            is_pos = tid in ground_truth_targets
            hits = candidate_blockers.get(tid, set())

            prov = CandidateProvenance(
                candidate_rank=rank,
                composite_priority=max(1.0, 10.0 - rank * 0.1),
                blocker_count=len(hits),
                exact_name_hit=1 if "exact_normalized_name" in hits else 0,
                compact_name_hit=1 if "compact_name" in hits else 0,
                name_token_hit=1 if "name_token" in hits else 0,
                ngram_hit=1 if "char_ngram" in hits else 0,
                address_token_hit=1 if "address_token" in hits else 0,
                structural_hit=1 if "address_structural" in hits else 0,
                source_is_s2=1 if tgt.source == "s2" or tid.startswith("S2") else 0,
            )

            if is_pos:
                positives.append((s1_record, tgt, prov, 1))
            else:
                neg_candidates_info.append((tid, rank, prov.composite_priority, len(hits)))

        # Also add any ground truth positives that were missed by blocker (rank=999)
        for true_tid in ground_truth_targets:
            if true_tid not in retrieved_set and true_tid in target_dict:
                tgt = target_dict[true_tid]
                prov = CandidateProvenance(
                    candidate_rank=999,
                    composite_priority=0.0,
                    blocker_count=0,
                    source_is_s2=1 if tgt.source == "s2" or true_tid.startswith("S2") else 0,
                )
                positives.append((s1_record, tgt, prov, 1))

        # 2. Select negatives according to strategy
        n_pos = len(positives)
        target_n_neg = max(negative_ratio, n_pos * negative_ratio)

        selected_neg_tids: list[str] = []

        if negative_strategy == "all" or len(neg_candidates_info) <= target_n_neg:
            # Strategy A: All available surviving negatives
            selected_neg_tids = [info[0] for info in neg_candidates_info]

        elif negative_strategy == "random":
            # Strategy B: Random subsample of candidates
            sample_size = min(len(neg_candidates_info), target_n_neg)
            sampled = self.rng.sample(neg_candidates_info, sample_size)
            selected_neg_tids = [info[0] for info in sampled]

        elif negative_strategy == "hard_similarity":
            # Strategy C: Hardest negatives by name similarity
            scored = []
            for tid, rank, prio, bcnt in neg_candidates_info:
                sim = jaro_winkler_similarity(s1_record.name.normalized, target_dict[tid].name.normalized)
                scored.append((sim, tid))
            scored.sort(reverse=True, key=lambda x: x[0])
            selected_neg_tids = [tid for _, tid in scored[:target_n_neg]]

        elif negative_strategy == "blocker_overlap":
            # Strategy D: Blocker-overlap hard negatives (highest blocker count / priority)
            sorted_by_overlap = sorted(neg_candidates_info, key=lambda x: (x[3], -x[1]), reverse=True)
            selected_neg_tids = [info[0] for info in sorted_by_overlap[:target_n_neg]]

        else:
            raise ValueError(f"Unknown negative strategy: {negative_strategy}")

        negatives: list[tuple[BusinessRecord, BusinessRecord, CandidateProvenance, int]] = []
        for tid in selected_neg_tids:
            tgt = target_dict[tid]
            rank = next((info[1] for info in neg_candidates_info if info[0] == tid), 50)
            hits = candidate_blockers.get(tid, set())
            prov = CandidateProvenance(
                candidate_rank=rank,
                composite_priority=max(1.0, 10.0 - rank * 0.1),
                blocker_count=len(hits),
                exact_name_hit=1 if "exact_normalized_name" in hits else 0,
                compact_name_hit=1 if "compact_name" in hits else 0,
                name_token_hit=1 if "name_token" in hits else 0,
                ngram_hit=1 if "char_ngram" in hits else 0,
                address_token_hit=1 if "address_token" in hits else 0,
                structural_hit=1 if "address_structural" in hits else 0,
                source_is_s2=1 if tgt.source == "s2" or tid.startswith("S2") else 0,
            )
            negatives.append((s1_record, tgt, prov, 0))

        info = {
            "num_candidates": len(candidates),
            "num_positives": len(positives),
            "num_negatives_available": len(neg_candidates_info),
            "num_negatives_selected": len(negatives),
        }

        return positives + negatives, info

    def build_dataset(
        self,
        s1_records: Sequence[BusinessRecord],
        target_dict: dict[str, BusinessRecord],
        ground_truth: dict[str, set[str]],
        blocker: CompositeBlocker,
        negative_strategy: str = "random",
        negative_ratio: int = 5,
        max_queries: int | None = None,
        progress_callback: Callable[[int, int], None] | None = None,
    ) -> tuple[np.ndarray, np.ndarray, list[str], list[str], DatasetStats]:
        """
        Build feature matrix X and label vector y for a cohort of S1 records.

        Returns
        -------
        X: np.ndarray of shape (N, num_features)
        y: np.ndarray of shape (N,)
        pair_s1_ids: list of S1 entity IDs
        pair_target_ids: list of target entity IDs
        stats: DatasetStats summary
        """
        all_pairs: list[tuple[BusinessRecord, BusinessRecord, CandidateProvenance, int]] = []
        queries = s1_records if max_queries is None else s1_records[:max_queries]
        total_queries = len(queries)

        total_pos = 0
        total_neg = 0
        hardest_sims: list[float] = []

        for i, s1 in enumerate(queries):
            cands, attribution = blocker.query(s1, track_attribution=True)
            gt_targets = ground_truth.get(s1.entity_id, set())

            pairs, info = self.build_pairs_for_query(
                s1_record=s1,
                target_dict=target_dict,
                ground_truth_targets=gt_targets,
                candidates=cands,
                blocker_attribution=attribution,
                negative_strategy=negative_strategy,
                negative_ratio=negative_ratio,
            )
            all_pairs.extend(pairs)

            n_p = info["num_positives"]
            n_n = info["num_negatives_selected"]
            total_pos += n_p
            total_neg += n_n

            # Track hardest negative similarity for this entity if any negatives exist
            entity_neg_sims = [
                jaro_winkler_similarity(s1.name.normalized, p[1].name.normalized)
                for p in pairs
                if p[3] == 0
            ]
            if entity_neg_sims:
                hardest_sims.append(max(entity_neg_sims))

            if progress_callback and (i + 1) % 500 == 0:
                progress_callback(i + 1, total_queries)

        N = len(all_pairs)
        pair_s1_ids = [p[0].entity_id for p in all_pairs]
        pair_target_ids = [p[1].entity_id for p in all_pairs]
        y = np.array([p[3] for p in all_pairs], dtype=np.int32)

        # Batch feature extraction
        feature_tuples = [(p[0], p[1], p[2]) for p in all_pairs]
        X = self.feature_extractor.extract_batch(feature_tuples)

        pos_ratio = (total_pos / N) if N > 0 else 0.0
        neg_per_ent = (total_neg / total_queries) if total_queries > 0 else 0.0
        hard_mean = float(np.mean(hardest_sims)) if hardest_sims else 0.0
        hard_max = float(np.max(hardest_sims)) if hardest_sims else 0.0

        stats = DatasetStats(
            num_queries=total_queries,
            num_positives=total_pos,
            num_negatives=total_neg,
            positive_ratio=pos_ratio,
            negatives_per_entity_mean=neg_per_ent,
            strategy=negative_strategy,
            hardest_negative_sim_mean=hard_mean,
            hardest_negative_sim_max=hard_max,
        )

        return X, y, pair_s1_ids, pair_target_ids, stats

    @staticmethod
    def save_dataset(
        filepath: str | Path,
        X: np.ndarray,
        y: np.ndarray,
        s1_ids: list[str],
        target_ids: list[str],
        feature_names: list[str],
    ) -> None:
        """Save dataset to .npz file."""
        Path(filepath).parent.mkdir(parents=True, exist_ok=True)
        np.savez_compressed(
            filepath,
            X=X,
            y=y,
            s1_ids=np.array(s1_ids, dtype=object),
            target_ids=np.array(target_ids, dtype=object),
            feature_names=np.array(feature_names, dtype=object),
        )

    @staticmethod
    def load_dataset(filepath: str | Path) -> tuple[np.ndarray, np.ndarray, list[str], list[str], list[str]]:
        """Load dataset from .npz file."""
        data = np.load(filepath, allow_pickle=True)
        return (
            data["X"],
            data["y"],
            list(data["s1_ids"]),
            list(data["target_ids"]),
            list(data["feature_names"]),
        )
